using System.Collections.Generic;
using Semblance.Core;
using UnityEngine;

namespace Semblance.Audio
{
    /// <summary>What a sound is for. Each bus has its own level, and some duck others so the important thing is heard.</summary>
    public enum AudioBus
    {
        /// <summary>Pick from the clip name (the default).</summary>
        Auto,
        /// <summary>Beds that are always there: wind, crickets, room tone, drones, lamp hum.</summary>
        Ambience,
        /// <summary>Ordinary things in the world: footsteps, doors, birds, the car, a TV.</summary>
        World,
        /// <summary>Things the player must notice: knocks, whispers, the creature, stingers, the bell.</summary>
        Cue,
        /// <summary>Residents talking.</summary>
        Voice,
        /// <summary>Interface clicks, the camera, the typewriter.</summary>
        UI,
        /// <summary>The chase, the menu theme, the jukebox.</summary>
        Music,
    }

    /// <summary>
    /// Plays sounds by name from Resources/Audio (generated by Semblance > Generate Audio): one-shots in 2D or at a
    /// point in the world, and looping sources. Every source goes through a small mixer: a level per bus, ducking
    /// (ambience dips under cues and conversation), a natural distance curve, distance and occlusion muffling for
    /// world sounds, and reverb only where it belongs.
    /// </summary>
    public class GameAudio : MonoBehaviour
    {
        private static GameAudio instance;
        private static readonly Dictionary<string, AudioClip> Cache = new Dictionary<string, AudioClip>();

        private sealed class Voice
        {
            public AudioSource Source;
            public AudioLowPassFilter LowPass;
            public AudioBus Bus;
            public float BaseVolume;
            public float Occlusion = 1f;      // 1 = clear line to the listener
            public float OcclusionTarget = 1f;
            public float NextOcclusionCheck;
            public bool Pooled;
        }

        private readonly List<Voice> voices = new List<Voice>();
        private readonly Dictionary<AudioSource, Voice> bySource = new Dictionary<AudioSource, Voice>();
        private readonly List<Voice> pool = new List<Voice>();
        private const int MaxPool = 40;

        // Mix levels: ambience sits well under everything; cues sit on top.
        private static readonly Dictionary<AudioBus, float> BusLevel = new Dictionary<AudioBus, float>
        {
            { AudioBus.Ambience, 0.6f }, { AudioBus.World, 1f }, { AudioBus.Cue, 1.15f },
            { AudioBus.Voice, 0.9f }, { AudioBus.UI, 0.7f }, { AudioBus.Music, 0.8f },
        };

        private static float duckAmount, duckUntil, duckCurrent;
        private static AnimationCurve rolloff;
        private Transform listener;

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        private static void ResetStatics()
        {
            instance = null;
            Cache.Clear();
            duckAmount = duckUntil = duckCurrent = 0f;
        }

        private static GameAudio Instance
        {
            get
            {
                if (instance == null)
                {
                    var go = new GameObject("Game Audio");
                    DontDestroyOnLoad(go);
                    instance = go.AddComponent<GameAudio>();
                }
                return instance;
            }
        }

        /// <summary>Natural falloff: loud close up, a long quiet tail, silent at max distance.</summary>
        private static AnimationCurve Rolloff => rolloff ??= new AnimationCurve(
            new Keyframe(0f, 1f, 0f, -4f), new Keyframe(0.12f, 0.62f), new Keyframe(0.3f, 0.3f),
            new Keyframe(0.6f, 0.1f), new Keyframe(1f, 0f, -0.1f, 0f));

        // ------------------------------------------------------------ Clips

        /// <summary>
        /// Loads and decodes every clip up front (a few MB), so the first scare of the night doesn't stall the frame
        /// on a disk read and decode.
        /// </summary>
        public static void WarmClips()
        {
            foreach (var clip in Resources.LoadAll<AudioClip>("Audio"))
            {
                if (clip == null) continue;
                Cache[clip.name] = clip;
                if (clip.loadState == AudioDataLoadState.Unloaded) clip.LoadAudioData();
            }
        }

        public static AudioClip Clip(string name)
        {
            if (string.IsNullOrEmpty(name))
                return null;
            if (!Cache.TryGetValue(name, out var clip))
            {
                clip = Resources.Load<AudioClip>("Audio/" + name);
                Cache[name] = clip;
            }
            return clip;
        }

        /// <summary>Picks one of name_1..name_n at random (falls back to plain name).</summary>
        public static AudioClip Variant(string name, int count)
        {
            var clip = Clip($"{name}_{Random.Range(1, count + 1)}");
            return clip != null ? clip : Clip(name);
        }

        /// <summary>Which bus a clip belongs on, from its name.</summary>
        public static AudioBus BusFor(string clipName)
        {
            if (string.IsNullOrEmpty(clipName)) return AudioBus.World;
            string n = clipName.ToLowerInvariant();
            if (n.StartsWith("voice_")) return AudioBus.Voice;
            if (n.StartsWith("sting") || n.StartsWith("creature") || n.StartsWith("knock") || n.StartsWith("whisper")
                || n.StartsWith("bell") || n.StartsWith("heartbeat") || n.StartsWith("breathing") || n.StartsWith("lamp_die")
                || n.StartsWith("name_") || n.StartsWith("thud"))
                return AudioBus.Cue;
            if (n.StartsWith("typewriter") || n.StartsWith("page_flip") || n.StartsWith("camera_") || n.StartsWith("flashlight")
                || n.StartsWith("register") || n.StartsWith("ui_"))
                return AudioBus.UI;
            if (n.StartsWith("music") || n.StartsWith("chase") || n.StartsWith("jukebox")) return AudioBus.Music;
            if (n.StartsWith("wind") || n.StartsWith("crickets") || n.StartsWith("room_tone") || n.StartsWith("drone")
                || n.StartsWith("lamp_buzz") || n.StartsWith("static"))
                return AudioBus.Ambience;
            return AudioBus.World;
        }

        // ------------------------------------------------------------ Playing

        public static void Play(string name, float volume = 1f, float pitch = 1f, AudioBus bus = AudioBus.Auto) => Play(Clip(name), volume, pitch, bus);

        public static void Play(AudioClip clip, float volume = 1f, float pitch = 1f, AudioBus bus = AudioBus.Auto)
        {
            if (clip == null) return;
            var v = Instance.GetPooled();
            if (v == null) return;
            v.Bus = bus == AudioBus.Auto ? BusFor(clip.name) : bus;
            var s = v.Source;
            s.spatialBlend = 0f;
            s.transform.position = Vector3.zero;
            s.bypassReverbZones = v.Bus != AudioBus.World;
            v.LowPass.enabled = false;
            Start(v, clip, volume, pitch);
        }

        public static void PlayAt(string name, Vector3 position, float volume = 1f, float pitch = 1f, float maxDistance = 30f, AudioBus bus = AudioBus.Auto)
            => PlayAt(Clip(name), position, volume, pitch, maxDistance, bus);

        public static void PlayAt(AudioClip clip, Vector3 position, float volume = 1f, float pitch = 1f, float maxDistance = 30f, AudioBus bus = AudioBus.Auto)
        {
            if (clip == null) return;
            var v = Instance.GetPooled();
            if (v == null) return;
            v.Bus = bus == AudioBus.Auto ? BusFor(clip.name) : bus;
            var s = v.Source;
            s.transform.position = position;
            Spatialize(s, maxDistance, v.Bus);
            s.bypassReverbZones = false;
            v.LowPass.enabled = true;
            v.Occlusion = v.OcclusionTarget = Instance.Occluded(position) ? OccludedGain : 1f;
            v.NextOcclusionCheck = 0f;
            Start(v, clip, volume, pitch);
            Caption(clip.name, position, maxDistance);
        }

        /// <summary>A looping source attached to a transform (or 2D if parent is null).</summary>
        public static AudioSource Loop(string name, Transform parent, float volume, float maxDistance = 20f, AudioBus bus = AudioBus.Auto)
        {
            var clip = Clip(name);
            var go = new GameObject("Loop " + name);
            // 2D loops live in the current scene so they stop when it unloads.
            if (parent != null)
                go.transform.SetParent(parent, false);
            var source = go.AddComponent<AudioSource>();
            source.clip = clip;
            source.loop = true;
            source.playOnAwake = false;
            source.dopplerLevel = 0f;
            var v = new Voice { Source = source, LowPass = go.AddComponent<AudioLowPassFilter>(), BaseVolume = volume };
            v.Bus = bus == AudioBus.Auto ? BusFor(name) : bus;
            if (parent != null)
            {
                Spatialize(source, maxDistance, v.Bus);
                source.bypassReverbZones = false;
                v.LowPass.enabled = true;
            }
            else
            {
                source.spatialBlend = 0f;
                source.bypassReverbZones = true;
                v.LowPass.enabled = false;
            }
            Instance.Track(v);
            source.volume = Instance.Mixed(v);
            if (clip != null)
            {
                source.time = Random.Range(0f, clip.length);
                source.Play();
            }
            return source;
        }

        /// <summary>Sets a loop's own level; the mixer applies bus level, ducking and occlusion on top.</summary>
        public static void SetVolume(AudioSource source, float volume)
        {
            if (source == null) return;
            if (instance != null && instance.bySource.TryGetValue(source, out var v)) v.BaseVolume = volume;
            else source.volume = volume;
        }

        public static float GetVolume(AudioSource source)
        {
            if (source == null) return 0f;
            return instance != null && instance.bySource.TryGetValue(source, out var v) ? v.BaseVolume : source.volume;
        }

        /// <summary>Dips ambience (and music a little) so something important can be heard.</summary>
        public static void Duck(float amount, float seconds)
        {
            duckAmount = Mathf.Max(Time.unscaledTime < duckUntil ? duckAmount : 0f, Mathf.Clamp01(amount));
            duckUntil = Mathf.Max(duckUntil, Time.unscaledTime + seconds);
        }

        // ------------------------------------------------------------ Captions

        private static readonly (string prefix, string text)[] Captions =
        {
            ("knock", "knocking"), ("name_whisper", "someone whispers your name"), ("whisper", "whispering"),
            ("creature_step", "heavy footsteps"), ("creature_shriek", "a shriek"), ("bell_toll", "the church bell"),
            ("lamp_die", "a lamp pops and dies"), ("door_creak", "a door creaks"), ("knuckle_crack", "knuckles cracking"),
            ("hum_hymn", "someone humming a hymn"), ("footstep", "footsteps"), ("owl", "an owl"), ("thud", "a thud"),
        };
        private static readonly Dictionary<string, float> lastCaption = new Dictionary<string, float>();

        /// <summary>When captions are on, names a sound you'd need to hear and where it came from.</summary>
        private static void Caption(string clipName, Vector3 position, float maxDistance)
        {
            if (!GameSettings.SoundCaptions || string.IsNullOrEmpty(clipName) || UI.PlayerHUD.Instance == null) return;
            string text = null;
            foreach (var (prefix, caption) in Captions)
                if (clipName.StartsWith(prefix)) { text = caption; break; }
            if (text == null) return;
            if (lastCaption.TryGetValue(text, out float t) && Time.unscaledTime - t < 3f) return;
            var cam = UnityEngine.Camera.main;
            if (cam == null) return;
            Vector3 to = position - cam.transform.position;
            if (to.magnitude > maxDistance * 0.8f) return;
            lastCaption[text] = Time.unscaledTime;
            Vector3 local = cam.transform.InverseTransformDirection(to);
            string where = to.magnitude < 2f ? "right beside you" : local.z < -Mathf.Abs(local.x) ? "behind you" : local.x > Mathf.Abs(local.z) * 0.6f ? "to your right"
                : local.x < -Mathf.Abs(local.z) * 0.6f ? "to your left" : "ahead";
            UI.PlayerHUD.Instance.Caption($"[{text}, {where}]");
        }

        // ------------------------------------------------------------ Internals

        private const float OccludedGain = 0.45f;

        private static void Spatialize(AudioSource s, float maxDistance, AudioBus bus)
        {
            s.spatialBlend = 1f;
            s.rolloffMode = AudioRolloffMode.Custom;
            s.SetCustomCurve(AudioSourceCurveType.CustomRolloff, Rolloff);
            s.minDistance = 1f;
            s.maxDistance = Mathf.Max(2f, maxDistance);
            s.spread = 0f;
            s.dopplerLevel = 0f;
            s.priority = bus == AudioBus.Cue ? 0 : bus == AudioBus.Ambience ? 200 : 128;
        }

        private static void Start(Voice v, AudioClip clip, float volume, float pitch)
        {
            var s = v.Source;
            v.BaseVolume = volume;
            s.pitch = pitch;
            s.clip = clip;
            s.loop = false;
            s.volume = Instance.Mixed(v);
            s.Play();
            // Anything the player has to notice gets room: the beds step back for it.
            if (v.Bus == AudioBus.Cue && volume > 0.2f)
                Duck(Mathf.Lerp(0.35f, 0.7f, Mathf.Clamp01(volume)), Mathf.Min(clip.length, 4f) + 0.5f);
        }

        private Voice GetPooled()
        {
            foreach (var v in pool)
                if (v.Source != null && !v.Source.isPlaying)
                    return v;
            if (pool.Count >= MaxPool)
            {
                // Steal the quietest non-cue sound rather than drop something important.
                Voice quietest = null;
                foreach (var v in pool)
                    if (v.Bus != AudioBus.Cue && (quietest == null || v.Source.volume < quietest.Source.volume))
                        quietest = v;
                quietest?.Source.Stop();
                return quietest;
            }
            var go = new GameObject("One Shot");
            go.transform.SetParent(transform, false);
            var source = go.AddComponent<AudioSource>();
            source.playOnAwake = false;
            source.dopplerLevel = 0f;
            var voice = new Voice { Source = source, LowPass = go.AddComponent<AudioLowPassFilter>(), Pooled = true };
            pool.Add(voice);
            Track(voice);
            return voice;
        }

        private void Track(Voice v)
        {
            voices.Add(v);
            bySource[v.Source] = v;
        }

        private static float BusGain(AudioBus bus)
        {
            float level = BusLevel.TryGetValue(bus, out var l) ? l : 1f;
            if (bus == AudioBus.Ambience) level *= GameSettings.AmbienceVolume;
            if (bus == AudioBus.Music) level *= GameSettings.MusicVolume;
            float duck = bus == AudioBus.Ambience ? duckCurrent : bus == AudioBus.Music || bus == AudioBus.World ? duckCurrent * 0.35f : 0f;
            return level * (1f - duck);
        }

        private float Mixed(Voice v) => v.BaseVolume * BusGain(v.Bus) * (v.Source.spatialBlend > 0.5f ? v.Occlusion : 1f);

        private bool Occluded(Vector3 position)
        {
            if (listener == null)
            {
                var l = FindAnyObjectByType<AudioListener>();
                if (l == null) return false;
                listener = l.transform;
            }
            Vector3 from = listener.position, to = position + Vector3.up * 0.1f;
            float dist = Vector3.Distance(from, to);
            if (dist < 1.5f) return false;
            // Something solid between you and it: a wall, a door, the ground.
            return Physics.Raycast(from, (to - from) / dist, dist - 0.6f, ~0, QueryTriggerInteraction.Ignore);
        }

        private void Update()
        {
            AudioListener.volume = GameSettings.MasterVolume;

            // Conversation pulls the beds down a little; cue ducks fade out smoothly.
            bool talking = Dialogue.DialogueUI.Instance != null && Dialogue.DialogueUI.Instance.Current != null;
            float target = Time.unscaledTime < duckUntil ? duckAmount : 0f;
            if (talking) target = Mathf.Max(target, 0.4f);
            float speed = target > duckCurrent ? 4f : 0.8f;
            duckCurrent = Mathf.MoveTowards(duckCurrent, target, Time.unscaledDeltaTime * speed);

            if (listener == null)
            {
                var l = FindAnyObjectByType<AudioListener>();
                if (l != null) listener = l.transform;
            }

            for (int i = voices.Count - 1; i >= 0; i--)
            {
                var v = voices[i];
                if (v.Source == null)
                {
                    voices.RemoveAt(i);
                    continue;
                }
                if (!v.Source.isPlaying && v.Pooled) continue;

                bool spatial = v.Source.spatialBlend > 0.5f;
                if (spatial && listener != null)
                {
                    if (Time.unscaledTime > v.NextOcclusionCheck)
                    {
                        v.NextOcclusionCheck = Time.unscaledTime + 0.2f + (i % 5) * 0.03f;
                        v.OcclusionTarget = Occluded(v.Source.transform.position) ? OccludedGain : 1f;
                    }
                    v.Occlusion = Mathf.MoveTowards(v.Occlusion, v.OcclusionTarget, Time.unscaledDeltaTime * 3f);
                    // Distance and walls take the top end off, so far-off and behind-the-wall sounds read as such.
                    float dist = Vector3.Distance(listener.position, v.Source.transform.position);
                    float far = Mathf.Clamp01(dist / Mathf.Max(v.Source.maxDistance, 1f));
                    float cutoff = Mathf.Lerp(16000f, 2200f, far * far);
                    cutoff *= Mathf.Lerp(0.07f, 1f, Mathf.InverseLerp(OccludedGain, 1f, v.Occlusion));
                    v.LowPass.cutoffFrequency = Mathf.Max(450f, cutoff);
                }
                v.Source.volume = Mixed(v);
            }
            if (Time.frameCount % 300 == 0)
            {
                foreach (var key in bySource.Keys)
                    if (key == null) bySourceCleanup.Add(key);
                foreach (var key in bySourceCleanup) bySource.Remove(key);
                bySourceCleanup.Clear();
            }
        }

        private readonly List<AudioSource> bySourceCleanup = new List<AudioSource>();
    }
}
